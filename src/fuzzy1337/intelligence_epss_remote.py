IMPORTER_ID = "epss-https-selection-acquisition"
IMPORTER_VERSION = "1"
ENVELOPE_ROLE = "epss-https-selected-snapshot"
RECEIPT_ROLE = "epss-https-selection-acquisition"
RAW_ROLE = "epss-https-gzip-source"
PARTIAL_ROLE = "epss-https-gzip-partial"
MAX_ENVELOPE_BYTES = 128 * 1024
MAX_RECEIPT_BYTES = 32 * 1024
RECEIVE_STATES = frozenset({"succeeded", "redirect-rejected", "http-rejected", "format-rejected",
                            "size-exceeded", "transport-failed", "timed-out"})


class EpssHttpsState(StrEnum):
    """Separate complete HTTPS custody from bounded import and publication failures."""

    SUCCEEDED = "succeeded"
    REDIRECT_REJECTED = "redirect-rejected"
    HTTP_REJECTED = "http-rejected"
    FORMAT_REJECTED = "format-rejected"
    TRANSPORT_FAILED = "transport-failed"
    TIMED_OUT = "timed-out"
    SIZE_EXCEEDED = "size-exceeded"
    DIGEST_MISMATCH = "digest-mismatch"
    PARSE_FAILED = "parse-failed"
    STORAGE_FAILED = "storage-failed"


class EpssHttpsAcknowledgement(StrEnum):
    """Report storage acknowledgement without inferring rollback or unobserved publication."""

    NOT_ATTEMPTED = "not-attempted"
    CONFIRMED = "confirmed"
    UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class EpssHttpsSource:
    """Select one immutable official archive path and mandatory caller-supplied byte pin.

    Publisher attribution records FIRST's source statements, not authentication or a
    verified data license. The only admitted locator is generated from commit and day.
    """

    commit: str
    score_date: str
    model_version: str
    expected_sha256: str

    def __post_init__(self) -> None:
        """Refuse aliases, alternate locators and malformed explicit source identity."""

        if type(self.commit) is not str or not re.fullmatch(r"[0-9a-f]{40}", self.commit):
            raise ValueError("EPSS HTTPS source requires an exact lowercase 40-hex commit")

        IntelligenceDate(self.score_date)
        IntelligenceText(self.model_version, "EPSS expected model version", 256)
        RequireReferenceDigest(self.expected_sha256)

    @property
    def SourceUrl(self) -> str:
        """Derive the sole query-free immutable HTTPS resource.

        Returns:
            Fixed raw GitHub archive URL containing only validated commit and calendar day.
        """

        return ("https://raw.githubusercontent.com/empiricalsec/epss_scores/"
                f"{self.commit}/{self.score_date[:4]}/epss_scores-{self.score_date}.csv.gz")

    def ToDict(self) -> dict[str, object]:
        """Bind pin, locator and honest primary attribution/terms links into source identity.

        Returns:
            Detached fixed source declaration without license or authenticity assumptions.
        """

        return {"commit": self.commit, "score_date": self.score_date,
                "model_version": self.model_version, "expected_sha256": self.expected_sha256,
                "source_url": self.SourceUrl,
                "publisher": "FIRST EPSS SIG; scores generated by Empirical Security",
                "attribution_url": "https://www.first.org/epss/faq",
                "data_url": "https://www.first.org/epss/data",
                "terms_urls": ["https://www.first.org/about/policies/terms"],
                "data_license": "not-established", "publisher_authentication": "not-assessed"}


@dataclass(frozen=True, slots=True)
class EpssHttpsRequest:
    """Admit one pinned HTTPS resource, canonical CVEs and bounded total receive limits."""

    source: EpssHttpsSource
    requested_ids: tuple[str, ...]
    max_bytes: int = MAX_COMPRESSED_BYTES
    timeout_seconds: float = 15.0

    def __post_init__(self) -> None:
        """Reject mutable selections, implicit identity, unbounded time and budget increases."""

        if type(self.source) is not EpssHttpsSource:
            raise ValueError("EPSS HTTPS acquisition requires an exact typed source")

        if type(self.requested_ids) is not tuple or self.requested_ids != RequestedIds(
            self.requested_ids,
        ):
            raise ValueError("EPSS request requires canonical immutable requested IDs")

        if type(self.max_bytes) is not int or not 1 <= self.max_bytes <= MAX_COMPRESSED_BYTES:
            raise ValueError("EPSS compressed ceiling must be positive and at most four MiB")

        if type(self.timeout_seconds) not in (int, float) or not (
            math.isfinite(self.timeout_seconds) and 0.05 <= self.timeout_seconds <= 60
        ):
            raise ValueError("EPSS timeout must be finite and in 0.05..60 seconds")


@dataclass(frozen=True, slots=True)
class EpssHttpsSelection:
    """Bind original HTTPS custody to selected decoder output under a separate envelope family."""

    source: EpssHttpsSource
    raw: EvidenceRecord
    selection: EpssSelection

    def __post_init__(self) -> None:
        """Validate structural joins; original-byte proof belongs to the reopening boundary."""

        if type(self.source) is not EpssHttpsSource or type(self.raw) is not EvidenceRecord or (
            type(self.selection) is not EpssSelection
        ):
            raise ValueError("EPSS envelope requires exact typed source, raw and selection")

        RequireRecord(self.raw, RAW_ROLE, "application/gzip")

        if (
            self.selection.raw_sha256 != self.raw.reference.sha256
            or self.selection.raw_size != self.raw.reference.size_bytes
            or self.selection.model_version != self.source.model_version
            or self.selection.score_date != self.source.score_date
            or self.source.expected_sha256 != self.raw.reference.sha256
            or self.selection.effective_at > self.raw.provenance.finished_at
        ):
            raise ValueError("EPSS envelope disagrees with original source selection")

    def ToDict(self) -> dict[str, object]:
        """Return detached envelope identity without legacy snapshot or authentication claims.

        Returns:
            Separate schema-one envelope containing unchanged schema-two decoder content.
        """

        provenance = self.raw.provenance
        attributed = {"source": self.source.ToDict(), "sha256": self.raw.reference.sha256,
                      "acquired_at": provenance.finished_at, "importer_id": IMPORTER_ID,
                      "importer_version": IMPORTER_VERSION, "transport": "https"}

        return {"schema_version": 1, "profile_version": 1,
                "profile": "epss-https-selected-acquisition", "source": self.source.ToDict(),
                "attributed_source": attributed, "raw": self.raw.ToDict(),
                "raw_id": self.raw.evidence_id, "selection": self.selection.ToDict(),
                "selection_reference": self.selection.Reference()}

    def Reference(self) -> str:
        """Bind original manifest, terms and complete selected content into a distinct identity.

        Returns:
            Deterministic attributed reference that cannot impersonate a legacy snapshot.
        """

        return "epss-https-selection:" + hashlib.sha256(
            CanonicalReferenceJson(self.ToDict()),
        ).hexdigest()

    def Serialize(self) -> bytes:
        """Return bounded canonical envelope bytes including their separate content reference.

        Returns:
            JSON payload within the explicit selected-envelope ceiling.
        """

        payload = CanonicalReferenceJson({**self.ToDict(), "reference": self.Reference()})

        if len(payload) > MAX_ENVELOPE_BYTES:
            raise ValueError("EPSS envelope exceeds its byte profile")

        return payload


@dataclass(frozen=True, slots=True)
class EpssHttpsOutcome:
    """Report actual HTTPS custody acknowledgements, including uncertain storage failure."""

    state: EpssHttpsState
    source: EpssHttpsSource
    requested_ids: tuple[str, ...]
    started_at: str
    finished_at: str
    received_bytes: int
    body_complete: bool
    max_bytes: int
    timeout_seconds: float
    receive_state: str
    http_status: int | None
    raw: EvidenceRecord | None = None
    envelope: EpssHttpsSelection | None = None
    selection_record: EvidenceRecord | None = None
    receipt: EvidenceRecord | None = None
    raw_ack: EpssHttpsAcknowledgement = EpssHttpsAcknowledgement.NOT_ATTEMPTED
    selection_ack: EpssHttpsAcknowledgement = EpssHttpsAcknowledgement.NOT_ATTEMPTED
    receipt_ack: EpssHttpsAcknowledgement = EpssHttpsAcknowledgement.NOT_ATTEMPTED

    def __post_init__(self) -> None:
        """Keep returned execution facts immutable without granting replay authority."""

        EpssHttpsRequest(self.source, self.requested_ids, self.max_bytes, self.timeout_seconds)

        if not isinstance(self.state, EpssHttpsState) or any(
            not isinstance(value, EpssHttpsAcknowledgement)
            for value in (self.raw_ack, self.selection_ack, self.receipt_ack)
        ):
            raise ValueError("EPSS outcome requires typed state and acknowledgement facts")

        if type(self.body_complete) is not bool or type(self.received_bytes) is not int or not (
            0 <= self.received_bytes <= self.max_bytes
        ):
            raise ValueError("EPSS outcome requires typed bounded byte completeness facts")

        if NormalizeEvidenceTime(self.started_at) != self.started_at or (
            NormalizeEvidenceTime(self.finished_at) != self.finished_at
            or self.finished_at < self.started_at
        ):
            raise ValueError("EPSS outcome requires canonical observed acquisition chronology")

        if type(self.receive_state) is not str or self.receive_state not in RECEIVE_STATES:
            raise ValueError("EPSS outcome requires an observed isolated-receiver state")

        if self.http_status is not None and (
            type(self.http_status) is not int or not 100 <= self.http_status <= 599
        ):
            raise ValueError("EPSS outcome requires a typed HTTP status or unknown status")

        if self.body_complete != (self.receive_state == "succeeded") or (
            self.body_complete and self.http_status != 200
        ):
            raise ValueError("EPSS outcome completeness disagrees with observed HTTPS facts")

        for record in (self.raw, self.selection_record, self.receipt):
            if record is not None and type(record) is not EvidenceRecord:
                raise ValueError("EPSS outcome requires immutable typed evidence handles")

        if self.envelope is not None and type(self.envelope) is not EpssHttpsSelection:
            raise ValueError("EPSS outcome requires a typed selected envelope")

    def ReceiptContent(self) -> dict[str, object]:
        """Describe terminal pre-receipt facts without circular self-publication assertions.

        Returns:
            Distinct bounded receipt body; receipt acknowledgement is outcome-only.
        """

        return {"schema_version": 1, "profile_version": 1,
                "profile": "epss-https-selected-acquisition", "state": self.state.value,
                "source": self.source.ToDict(), "requested_ids": list(self.requested_ids),
                "started_at": self.started_at, "finished_at": self.finished_at,
                "received_bytes": self.received_bytes, "body_complete": self.body_complete,
                "transport": "https", "http_status": self.http_status,
                "receive_state": self.receive_state,
                "limits": {"max_compressed_bytes": self.max_bytes,
                           "timeout_seconds": self.timeout_seconds,
                           "max_decoded_bytes": MAX_DECODED_BYTES, "max_csv_rows": MAX_CSV_ROWS},
                "raw": self.raw.ToDict() if self.raw is not None else None,
                "selection_record": (self.selection_record.ToDict()
                                     if self.selection_record is not None else None),
                "selection_reference": (self.envelope.Reference()
                                        if self.envelope is not None else None),
                "raw_ack": self.raw_ack.value, "selection_ack": self.selection_ack.value,
                "publisher_authentication": "not-assessed"}


def RequireRecord(record: EvidenceRecord, role: str, media_type: str) -> None:
    """Require this profile's artifact attribution before content reads or interpretation.

    Args:
        record: Exact selected immutable evidence manifest.
        role: Required artifact role in this distinct acquisition family.
        media_type: Required original or normalized content type.
    """

    if (
        record.reference.role != role or record.reference.media_type != media_type
        or record.provenance.source_id != IMPORTER_ID
        or record.provenance.source_version != IMPORTER_VERSION
        or record.provenance.tool_version is not None
        or record.provenance.invocation_sha256 is not None
        or record.provenance.execution is not None
    ):
        raise ValueError("EPSS artifact has foreign role, media type or importer provenance")


def AcquireHttpsEpssSelection(
    workspace_root: Path, request: EpssHttpsRequest, *, scope_reference: str,
) -> EpssHttpsOutcome:
    """Receive one pinned gzip and publish original custody, selection and receipt in owning stores.

    Args:
        workspace_root: Explicit existing owning workspace.
        request: Typed immutable source, finite receive limits and selected IDs.
        scope_reference: Explicit collection attribution, never execution authority.

    Returns:
        Honest terminal state and independent acknowledgements; failed publication may leave
        immutable artifacts and is never reported as rollback or successful complete custody.
    """

    if type(request) is not EpssHttpsRequest:
        raise ValueError("EPSS HTTPS acquisition requires a typed HTTPS request")

    RequireReferenceText(scope_reference, "scope_reference")
    owner = LocalWorkspaceStore(workspace_root).Open()
    store = LocalEvidenceStore(workspace_root / "evidence")
    started_at = datetime.now(timezone.utc).isoformat(timespec="microseconds")
    payload, receive_state, http_status = ReceiveIsolatedHttps(
        request.source.SourceUrl, request.max_bytes, request.timeout_seconds, accept_kind="gzip",
    )
    finished_at = datetime.now(timezone.utc).isoformat(timespec="microseconds")
    complete = receive_state == "succeeded"
    provenance = EvidenceProvenance(owner.workspace_id, scope_reference, IMPORTER_ID,
                                    IMPORTER_VERSION, None, started_at, finished_at)
    outcome = EpssHttpsOutcome(
        EpssHttpsState(receive_state),
        request.source, request.requested_ids, started_at, finished_at, len(payload),
        complete, request.max_bytes, request.timeout_seconds, receive_state, http_status,
    )

    try:
        outcome = replace(outcome, raw_ack=EpssHttpsAcknowledgement.UNKNOWN)
        raw = store.Put(payload, RAW_ROLE if complete else PARTIAL_ROLE,
                        "application/gzip", provenance)
        outcome = replace(outcome, raw=raw, raw_ack=EpssHttpsAcknowledgement.CONFIRMED)

        if complete:
            if request.source.expected_sha256 != raw.reference.sha256:
                outcome = replace(outcome, state=EpssHttpsState.DIGEST_MISMATCH)

            else:
                try:
                    selected = ParseEpssSelection(
                        payload, request.requested_ids, model_version=request.source.model_version,
                        score_date=request.source.score_date,
                    )
                    envelope = EpssHttpsSelection(request.source, raw, selected)
                    serialized = envelope.Serialize()

                except ValueError:
                    outcome = replace(outcome, state=EpssHttpsState.PARSE_FAILED)

                else:
                    outcome = replace(outcome, selection_ack=EpssHttpsAcknowledgement.UNKNOWN)
                    record = store.Put(serialized, ENVELOPE_ROLE, "application/json", provenance)
                    outcome = replace(outcome, envelope=envelope, selection_record=record,
                                      selection_ack=EpssHttpsAcknowledgement.CONFIRMED)

        serialized_receipt = CanonicalReferenceJson(outcome.ReceiptContent())

        if len(serialized_receipt) > MAX_RECEIPT_BYTES:
            return replace(outcome, state=EpssHttpsState.STORAGE_FAILED, envelope=None)

        outcome = replace(outcome, receipt_ack=EpssHttpsAcknowledgement.UNKNOWN)
        receipt = store.Put(serialized_receipt, RECEIPT_ROLE, "application/json", provenance)

        return replace(outcome, receipt=receipt, receipt_ack=EpssHttpsAcknowledgement.CONFIRMED)

    except EvidenceError:
        return replace(outcome, state=EpssHttpsState.STORAGE_FAILED, envelope=None)


def DecodeHttpsSource(value: object) -> EpssHttpsSource:
    """Reconstruct exact source fields and fixed primary-source attribution without network I/O.

    Args:
        value: Untrusted source object decoded from bounded persisted JSON.

    Returns:
        Strict immutable source with the generated locator and exact fixed attribution.
    """

    fields = RequireManifestFields(value, {"commit", "score_date", "model_version",
        "expected_sha256", "source_url", "publisher", "attribution_url", "data_url",
        "terms_urls", "data_license", "publisher_authentication"})
    source = EpssHttpsSource(cast(str, fields["commit"]), cast(str, fields["score_date"]),
                            cast(str, fields["model_version"]),
                            cast(str, fields["expected_sha256"]))

    if CanonicalReferenceJson(source.ToDict()) != CanonicalReferenceJson(value):
        raise ValueError("EPSS HTTPS source disagrees with its exact immutable identity")

    return source


def LoadHttpsEpssSelection(
    workspace_root: Path, selection_id: str, receipt_id: str,
) -> EpssHttpsSelection:
    """Reopen exact HTTPS custody roots and reparse complete original gzip before returning.

    Args:
        workspace_root: Explicit existing owning workspace, including relocated original stores.
        selection_id: Exact attributed selected-envelope manifest identifier.
        receipt_id: Exact successful terminal receipt from the same acquisition.

    Returns:
        Verified original-byte selection; inspection writes nothing and never authenticates
        the publisher, assigns target applicability or enters legacy snapshot dispatch.
    """

    owner = LocalWorkspaceStore(workspace_root).Open()
    store = BoundedEpssEvidenceStore(
        workspace_root / "evidence", ENVELOPE_ROLE, "application/json", MAX_ENVELOPE_BYTES,
    )
    receipts = BoundedEpssEvidenceStore(
        workspace_root / "evidence", RECEIPT_ROLE, "application/json", MAX_RECEIPT_BYTES,
    )
    selected_record = store.Get(selection_id)
    receipt = receipts.Get(receipt_id)
    RequireRecord(selected_record, ENVELOPE_ROLE, "application/json")
    RequireRecord(receipt, RECEIPT_ROLE, "application/json")

    if selected_record.provenance != receipt.provenance or (
        receipt.provenance.workspace_id != owner.workspace_id
    ):
        raise ValueError("EPSS selected custody requires identical owning acquisition provenance")

    document = JsonObject(
        ReadBounded(store, selected_record, MAX_ENVELOPE_BYTES), MAX_ENVELOPE_BYTES,
    )
    terminal = JsonObject(ReadBounded(receipts, receipt, MAX_RECEIPT_BYTES), MAX_RECEIPT_BYTES)
    raw = ParseEvidenceManifest(CanonicalReferenceJson(document.get("raw")))
    RequireRecord(raw, RAW_ROLE, "application/gzip")

    if raw.provenance != selected_record.provenance:
        raise ValueError("EPSS original raw facts disagree with selected receipt provenance")

    source = DecodeHttpsSource(document.get("source"))
    selection = DecodeSelection(document.get("selection"))
    limits = RequireManifestFields(terminal.get("limits"),
        {"max_compressed_bytes", "timeout_seconds", "max_decoded_bytes", "max_csv_rows"})
    request = EpssHttpsRequest(source, selection.requested_ids,
                               cast(int, limits["max_compressed_bytes"]),
                               cast(float, limits["timeout_seconds"]))
    envelope = EpssHttpsSelection(source, raw, selection)

    if raw.reference.size_bytes > request.max_bytes:
        raise ValueError("EPSS original raw facts disagree with selected receipt constraints")

    expected = EpssHttpsOutcome(
        EpssHttpsState.SUCCEEDED, source, selection.requested_ids,
        receipt.provenance.started_at, receipt.provenance.finished_at,
        raw.reference.size_bytes, True, request.max_bytes, request.timeout_seconds,
        "succeeded", 200, raw=raw, envelope=envelope,
        selection_record=selected_record, raw_ack=EpssHttpsAcknowledgement.CONFIRMED,
        selection_ack=EpssHttpsAcknowledgement.CONFIRMED,
    )

    if envelope.Serialize() != CanonicalReferenceJson(document) or (
        CanonicalReferenceJson(expected.ReceiptContent()) != CanonicalReferenceJson(terminal)
    ):
        raise ValueError("EPSS selected envelope or terminal receipt disagrees with exact custody")

    originals = BoundedEpssEvidenceStore(
        workspace_root / "evidence", RAW_ROLE, "application/gzip", request.max_bytes,
    )

    if originals.Get(raw.evidence_id) != raw:
        raise ValueError("EPSS original acquisition manifest is missing or foreign")

    reparsed = ParseEpssSelection(
        ReadBounded(originals, raw, request.max_bytes), selection.requested_ids,
        model_version=source.model_version, score_date=source.score_date,
    )

    if reparsed != selection:
        raise ValueError("EPSS selected content disagrees with original gzip bytes")

    return envelope
